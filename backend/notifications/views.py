# HTTP request handlers for in-app notices about marketplace activity.
# Read the permission settings, then the query filters, then the action methods to follow a request.
from rest_framework import viewsets, permissions
from rest_framework.decorators import action
from rest_framework.response import Response
from .models import Notification
from .serializers import NotificationSerializer
from .utils import publish_notifications
from django.db import transaction


class NotificationViewSet(viewsets.ModelViewSet):
    http_method_names = ['get', 'post', 'head', 'options']
    serializer_class = NotificationSerializer
    permission_classes = [permissions.IsAuthenticated]

    def get_queryset(self):
        return Notification.objects.filter(user=self.request.user).order_by('-created_at', '-id')

    def create(self, request, *args, **kwargs):
        return Response({'detail': 'Notifications are generated by marketplace events.'}, status=405)

    @action(detail=False, methods=['get'])
    def unread_count(self, request):
        return Response({'count': self.get_queryset().filter(is_read=False).count()})

    @action(detail=True, methods=['post'])
    def mark_read(self, request, pk=None):
        n = self.get_object()
        changed = self.get_queryset().filter(pk=n.pk, is_read=False).update(is_read=True)
        n.is_read = True
        if changed:
            transaction.on_commit(lambda: publish_notifications(request.user.pk))
        return Response(NotificationSerializer(n).data)

    @action(detail=False, methods=['post'])
    def mark_all_read(self, request):
        changed = self.get_queryset().filter(is_read=False).update(is_read=True)
        if changed:
            transaction.on_commit(lambda: publish_notifications(request.user.pk))
        return Response({'status': 'ok'})
